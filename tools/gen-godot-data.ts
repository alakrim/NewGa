// Generates the Godot client's data mirrors from the TypeScript game data, so they stay in sync:
//   godot/scripts/fl_data.gd      Frontline units / buildings / research / stances / plots
//   godot/scripts/heroes_data.gd  the 20 heroes (name, role, title, passive, abilities)
// Run:  npx tsx tools/gen-godot-data.ts
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FL, FL_BUILDING_ORDER, FL_BUILDINGS, FL_PLOTS, FL_RESEARCH, FL_UNIT_ORDER, FL_UNITS, STANCES, CASTLE, WATCHTOWER } from '../src/shared/frontline/data';
import { HEROES } from '../src/shared/data/heroes';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'godot', 'scripts');

/** GDScript literal for a JSON-like value. */
function gd(v: unknown, ind = 0): string {
  const pad = '\t'.repeat(ind + 1);
  const end = '\t'.repeat(ind);
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(Math.round(v * 1000) / 1000);
  if (typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x === 'number' || typeof x === 'string')) return `[${v.map((x) => gd(x)).join(', ')}]`;
    return `[\n${v.map((x) => pad + gd(x, ind + 1)).join(',\n')},\n${end}]`;
  }
  const o = v as Record<string, unknown>;
  return `{\n${Object.keys(o).map((k) => `${pad}${JSON.stringify(k)}: ${gd(o[k], ind + 1)}`).join(',\n')},\n${end}}`;
}

const HEADER = '# GENERATED by tools/gen-godot-data.ts from the TypeScript game data. Do not edit by hand; keep in sync by re-running:\n#   npx tsx tools/gen-godot-data.ts\n';

// ------------------------------------------------------------------ fl_data.gd
const units: Record<string, unknown> = {};
for (const id of FL_UNIT_ORDER) {
  const u = FL_UNITS[id];
  units[id] = {
    id, name: u.name, description: u.description, cost: u.cost, pop: u.pop, train_time: u.trainTime, trainer: u.trainer, role: u.role,
    hp: u.stats.maxHp, damage: u.stats.attackDamage, armor: u.stats.armor, range: u.stats.attackRange, speed: u.stats.moveSpeed,
    splash: u.splash ?? 0, heal: !!u.heal,
  };
}
const buildings: Record<string, unknown> = {};
for (const id of FL_BUILDING_ORDER) {
  const b = FL_BUILDINGS[id];
  buildings[id] = { id, name: b.name, description: b.description, cost: b.cost, build_time: b.buildTime, hp: b.hp, max: b.max ?? 0, requires: b.requires ?? '' };
}
const research: Record<string, unknown> = {};
for (const [k, r] of Object.entries(FL_RESEARCH)) research[k] = { name: r.name, text: r.text, costs: r.costs };
const stances: Record<string, unknown> = {};
for (const [k, s] of Object.entries(STANCES)) stances[k] = { name: s.name, key: s.key, text: s.text };

const fl = `${HEADER}class_name FlData
## Frontline data mirrored from src/shared/frontline/data.ts (keep in sync: re-run the generator).

const CONST := ${gd({
  max_pop: FL.maxPop, base_pop: FL.basePop, house_pop: FL.housePop, start_gold: FL.startGold, passive_gold: FL.passiveGold,
  min_x: FL.minX, max_x: FL.maxX, castle_hp: CASTLE.hp, watchtower_range: WATCHTOWER.range, banner_gold: FL.bannerGold, heart_gold: FL.heartGold,
})}

const UNIT_ORDER := ${gd([...FL_UNIT_ORDER])}
const UNITS := ${gd(units)}

const BUILDING_ORDER := ${gd([...FL_BUILDING_ORDER])}
const BUILDINGS := ${gd(buildings)}

const RESEARCH := ${gd(research)}

const STANCE_ORDER := ["garrison", "defend", "hold", "attack"]
const STANCES := ${gd(stances)}

## Building plots in index order: [team, slot, x, z]; each player owns 7 (team 0 slot 0, team 0 slot 1, team 1 slot 0, team 1 slot 1).
const PLOTS := ${gd(FL_PLOTS.map((p) => [p.team, p.slot, p.x, p.z]))}
`;
writeFileSync(join(root, 'fl_data.gd'), fl);

// ------------------------------------------------------------------ heroes_data.gd
const heroes = HEROES.map((h) => ({
  id: h.id, name: h.name, title: h.title, role: h.role, difficulty: h.difficulty, faction: h.faction, quote: h.quote,
  melee: h.attack.kind === 'melee',
  stats: { hp: h.base.maxHp, damage: h.base.attackDamage, armor: h.base.armor, range: h.base.attackRange, speed: h.base.moveSpeed, mana: h.base.maxMana },
  passive: { name: h.passive.name, description: h.passive.description },
  abilities: h.abilities.map((a) => ({
    name: a.name, description: a.description, targeting: a.targeting, range: a.range, radius: a.radius ?? 0, cooldown: a.cooldown, mana: a.manaCost,
  })),
}));
const out = `${HEADER}class_name HeroesData
## The 20 heroes (roster order), mirrored from src/shared/data/heroes/*.ts (keep in sync: re-run the generator).

const ROLES := ["Tank", "Fighter", "Assassin", "Mage", "Marksman", "Support"]
const SLOT_KEYS := ["Q", "W", "E", "R"]
const HEROES := ${gd(heroes)}


static func by_id(id: String) -> Dictionary:
	for h in HEROES:
		if h.id == id:
			return h
	return {}
`;
writeFileSync(join(root, 'heroes_data.gd'), out);
console.log(`wrote fl_data.gd (${FL_UNIT_ORDER.length} units, ${FL_BUILDING_ORDER.length} buildings) and heroes_data.gd (${HEROES.length} heroes)`);
