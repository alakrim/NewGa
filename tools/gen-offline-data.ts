// Exports the game data the GDScript offline engine (godot/offline/engine/) needs, straight from the TypeScript
// sources, so heroes, abilities, units and numbers stay one source of truth:
//   npx tsx tools/gen-offline-data.ts   ->  godot/offline/data.json
// tests/offline.test.ts fails when the committed file is stale.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HEROES } from '../src/shared/data/heroes';
import { COMBAT, ECON, MAX_LEVEL, SIGHT, TICK_RATE, TIMING, XP, XP_TABLE } from '../src/shared/constants';
import { MAP } from '../src/shared/map';
import { SUMMONS, TOWERS, ZERO_STATS } from '../src/shared/units';
import {
  CASTLE, FL, FL_BANNERS, FL_BUILDING_ORDER, FL_BUILDINGS, FL_NODES, FL_PLOTS, FL_RESEARCH, FL_UNIT_ORDER, FL_UNITS, MINE,
  PLAYER_COLORS, PLAYER_HEX, STANCE_ORDER, WATCHTOWER,
} from '../src/shared/frontline/data';
import { PLANS } from '../src/shared/frontline/bot';
import { abilityIntent } from '../src/shared/sim/bots';

export function offlineData() {
  return {
    about: 'GENERATED by tools/gen-offline-data.ts from src/shared. Do not edit; re-run the tool.',
    stat_keys: Object.keys(ZERO_STATS),
    const: { TICK_RATE, MAX_LEVEL, XP_TABLE, ECON, XP, SIGHT, TIMING, COMBAT, MAP },
    heroes: HEROES,
    // what bots use each ability for (help / harm / summon / self), precomputed from the effect trees
    intents: Object.fromEntries(HEROES.map((h) => [h.id, h.abilities.map((a) => abilityIntent(a))])),
    summons: SUMMONS,
    towers: { fortress: TOWERS.fortress, arrow: TOWERS.arrow },
    fl: FL,
    units: FL_UNITS,
    unit_order: FL_UNIT_ORDER,
    buildings: FL_BUILDINGS,
    building_order: FL_BUILDING_ORDER,
    research: FL_RESEARCH,
    plots: FL_PLOTS,
    nodes: FL_NODES,
    banners: FL_BANNERS,
    mine: MINE,
    castle: CASTLE,
    watchtower: WATCHTOWER,
    player_colors: PLAYER_COLORS,
    player_hex: PLAYER_HEX,
    stances: STANCE_ORDER,
    plans: PLANS,
  };
}

export const OFFLINE_DATA_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'godot', 'offline', 'data.json');

if (process.argv[1] && /gen-offline-data/.test(process.argv[1])) {
  writeFileSync(OFFLINE_DATA_PATH, JSON.stringify(offlineData()) + '\n');
  console.log('wrote', OFFLINE_DATA_PATH);
}
